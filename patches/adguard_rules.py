"""Downloads AdGuard filter lists and converts their whole-domain network rules
into cobalt/network/adguard_rules.inc for adguard_filter.cc.

Usage: python3 adguard_rules.py <output .inc> [filter ids...]   (default ids: 2 3 11)
  2  = AdGuard Base filter
  3  = AdGuard Tracking Protection filter
  11 = AdGuard Mobile Ads filter
Kept: "||host^" rules (optionally "$third-party"/"$3p", "$important", "$all") and their
"@@||host^" exceptions. Skipped (counted): cosmetic rules, path/regex rules and rules limited
to content types or domains, which need a full page engine.
"""
import re, sys, urllib.request

out = sys.argv[1]
ids = sys.argv[2:] or ['2', '3', '11']
URL = 'https://filters.adtidy.org/extension/chromium/filters/%s.txt'

HOST = re.compile(r'^\|\|([a-z0-9][a-z0-9.-]*\.[a-z0-9-]+)\^\|?$')
COSMETIC = ('##', '#@#', '#?#', '#@?#', '#$#', '#@$#', '#%#', '#@%#', '$$', '$@$')
BLOCK_OK = {'third-party', '3p', 'important', 'all', 'document'}
ALLOW_OK = {'important', 'all', 'document'}

important, block_all, block_3p, allow = set(), set(), set(), set()
stats = {'lines': 0, 'kept': 0, 'cosmetic': 0, 'other': 0}
info = []
for fid in ids:
    req = urllib.request.Request(URL % fid, headers={'User-Agent': 'cobalt-build'})
    text = urllib.request.urlopen(req, timeout=60).read().decode('utf-8', 'replace')
    title = version = ''
    for line in text.splitlines():
        line = line.strip()
        if line.startswith('! Title:') and not title:
            title = line[8:].strip()
        elif line.startswith('! Version:') and not version:
            version = line[10:].strip()
        if not line or line.startswith('!') or line.startswith('['):
            continue
        stats['lines'] += 1
        if any(c in line for c in COSMETIC):
            stats['cosmetic'] += 1
            continue
        exc = line.startswith('@@')
        body = line[2:] if exc else line
        pat, _, mods = body.partition('$')
        m = HOST.match(pat.lower())
        modset = {x.strip().lower() for x in mods.split(',')} - {''} if mods else set()
        ok = ALLOW_OK if exc else BLOCK_OK
        if not m or not modset <= ok:
            stats['other'] += 1
            continue
        host = m.group(1)
        stats['kept'] += 1
        if exc:
            allow.add(host)
        elif 'important' in modset and not ({'third-party', '3p'} & modset):
            important.add(host)
        elif {'third-party', '3p'} & modset:
            block_3p.add(host)
        else:
            block_all.add(host)
    info.append('%s %s' % (title or 'filter ' + fid, version))

block_3p -= block_all


def blob(name, hosts):
    lines = ['static const char %s[] =' % name]
    for h in sorted(hosts):
        lines.append('    "%s\\n"' % h)
    if not hosts:
        lines.append('    ""')
    lines[-1] += ';'
    return '\n'.join(lines) + '\n'


summary = '; '.join(info)
with open(out, 'w', encoding='ascii', newline='\n') as f:
    f.write('// Generated by patches/adguard_rules.py - do not edit.\n')
    f.write('// %s\n// %s\n\n' % (summary, stats))
    f.write('static const char kAdgInfo[] = "%s";\n\n' % summary.replace('"', "'"))
    f.write(blob('kAdgImportant', important))
    f.write(blob('kAdgBlockAll', block_all))
    f.write(blob('kAdgBlock3p', block_3p))
    f.write(blob('kAdgAllow', allow))
print(summary)
print(stats, 'important', len(important), 'block', len(block_all), 'block-3p', len(block_3p),
      'allow', len(allow))
